export function getSuggestions(exerciseId: string, allExercises: Exercise[]): Exercise[] {
  const target = allExercises.find(e => e.id === exerciseId);
  if (!target) return [];

  return allExercises
    .filter(e => e.id !== exerciseId)
    .map(e => {
      let score = 0;
      if (e.primaryMuscle === target.primaryMuscle) score += 3;
      if (e.movementPattern === target.movementPattern) score += 2;
      if (target.secondaryMuscles.some(m => e.primaryMuscle === m || e.secondaryMuscles.includes(m))) score += 1;
      return { exercise: e, score };
    })
    .filter(x => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, 6)
    .map(x => x.exercise);
}
